#!/usr/bin/env python3
"""Rebuilds Sources/HSBGMacOverlay/TavernPoolSeed.swift, the offline seed of the tavern list.

Usage: curl -o /tmp/cards.json https://api.hearthstonejson.com/v1/latest/enUS/cards.json
       python3 -I scripts/update-tavern-seed.py /tmp/cards.json

Same filter as TavernPool.parse: Solo pool minions and pool spells, tiers 1-7, no Duos-only cards.
Card data from HearthstoneJSON (CC0); the card texts and names are (c) Blizzard Entertainment.
"""
import json
import pathlib
import sys

# Display-only tags that no filter uses; everything else is kept for TavernFilterKey.
NOISE = {"TRIGGER_VISUAL", "AURA", "InvisibleDeathrattle"}


def slim(card):
    minion = bool(card.get("isBattlegroundsPoolMinion"))
    races = card.get("races") or ([card["race"]] if card.get("race") else [])
    out = {
        "id": card["id"],
        "name": card["name"],
        "tier": card["techLevel"],
        "isSpell": not minion,
        "races": [r for r in races if r != "INVALID"] if minion else [],
        "associatedRaces": card.get("battlegroundsAssociatedRaces") or [],
        "mechanics": [m for m in card.get("mechanics", []) if m not in NOISE],
        "referencedTags": card.get("referencedTags") or [],
        "text": card.get("text") or "",
    }
    if minion:
        for key in ("attack", "health"):
            if key in card:
                out[key] = card[key]
    elif "cost" in card:
        out["cost"] = card["cost"]
    return out


def main(path):
    cards = json.load(open(path, encoding="utf-8"))
    pool = [
        slim(c) for c in cards
        if (c.get("isBattlegroundsPoolMinion") or c.get("isBattlegroundsPoolSpell"))
        and not c.get("isBattlegroundsDuosExclusive")
        and c.get("name") and c.get("id") and 1 <= (c.get("techLevel") or 0) <= 7
    ]
    pool.sort(key=lambda c: (c["tier"], c["name"], c["id"]))
    text = json.dumps(pool, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    assert '"#' not in text, "the raw string delimiter would break"
    # One card per line keeps diffs readable.
    text = text.replace("},{", "},\n{")
    target = pathlib.Path(__file__).resolve().parent.parent / "Sources/HSBGMacOverlay/TavernPoolSeed.swift"
    target.write_text(
        "// Generated by scripts/update-tavern-seed.py from HearthstoneJSON (CC0). Card names (c) Blizzard Entertainment.\n"
        "// Offline seed of the tavern list; the app replaces it with a fresher download when it can.\n"
        "import Foundation\n\n"
        "enum TavernPoolSeed {\n"
        f"    /// {sum(not c['isSpell'] for c in pool)} minions and {sum(c['isSpell'] for c in pool)} spells.\n"
        "    static let cards: [PoolCard] = (try? JSONDecoder().decode([PoolCard].self, from: Data(json.utf8))) ?? []\n\n"
        '    private static let json = #"""\n' + text + '\n"""#\n}\n',
        encoding="utf-8",
    )
    print(f"wrote {target} with {len(pool)} cards")


if __name__ == "__main__":
    main(sys.argv[1])
